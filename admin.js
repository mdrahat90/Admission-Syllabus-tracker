/* Admin tool: validate a syllabus file, then download it as data/syllabus.js or preview it in the app on this device. */
(function () {
  "use strict";
  var C = window.PoridhiCore, S = window.PoridhiStore;
  var reportEl = document.getElementById("report"), currentEl = document.getElementById("current"), removeBtn = document.getElementById("remove");
  var last = null;

  function esc(v) { return String(v === null || v === undefined ? "" : v).replace(/[&<>"']/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]; }); }

  function download(name, text, type) {
    var blob = new Blob([text], { type: type }), url = URL.createObjectURL(blob), a = document.createElement("a");
    a.href = url; a.download = name; document.body.appendChild(a); a.click(); a.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
  }

  function showCurrent() {
    var ov = S.getOverride();
    var parts = [];
    parts.push(window.PORIDHI_SYLLABUS ? "A syllabus is installed with the app." : "No syllabus is installed with the app yet.");
    if (ov) parts.push("A preview import is active on this device" + (ov.filename ? " (" + esc(ov.filename) + ", " + esc(new Date(ov.importedAt).toLocaleString()) + ")" : "") + ". The app is using it instead.");
    currentEl.innerHTML = parts.join(" ");
    removeBtn.hidden = !ov;
  }

  function issues(list, title, cls) {
    if (!list.length) return "";
    return '<section class="card"><h2 class="h2">' + title + " (" + list.length + ")</h2><ul class=\"issues\">" +
      list.map(function (i) { return "<li><b>" + esc(i.where) + ":</b> " + esc(i.msg) + "</li>"; }).join("") + "</ul></section>";
  }

  function render(res, name) {
    var html = "";
    if (res.ok) {
      var ix = C.buildIndex(res.data);
      html += '<p class="status-ok" role="status">' + esc(name) + " passed validation (" + res.format.toUpperCase() + "). " + res.counts.programmes + " programmes, " + res.counts.subjects + " subjects, " + res.counts.chapters + " chapters, " + res.counts.topics + " topics." +
        (res.warnings.length ? " " + res.warnings.length + " warning(s) to review." : "") + "</p>";
      html += '<section class="card"><h2 class="h2">What each programme will show</h2><div style="overflow-x:auto"><table class="table"><thead><tr><th>Programme</th><th class="n">Subjects</th><th class="n">Chapters</th><th class="n">Topics counted</th><th class="n">Conditional</th></tr></thead><tbody>' +
        res.data.programmes.map(function (p) {
          var v = ix.view(p.programme_id), ch = 0, cond = 0;
          v.subjects.forEach(function (se) { ch += se.chapters.length; });
          Object.keys(v.topicInfo).forEach(function (t) { if (v.topicInfo[t].applicability === "conditional") cond++; });
          return "<tr><td>" + esc(p.programme_name) + " <span class=\"hint\">" + esc(p.programme_id) + '</span></td><td class="n">' + v.subjects.length + '</td><td class="n">' + ch + '</td><td class="n">' + v.total + '</td><td class="n">' + cond + "</td></tr>";
        }).join("") + "</tbody></table></div></section>";
    } else {
      html += '<p class="status-bad" role="alert">' + esc(name) + " has " + res.errors.length + " error(s). Fix them and choose the file again. Nothing was installed.</p>";
    }
    html += issues(res.errors, "Errors", "bad") + issues(res.warnings, "Warnings");
    if (res.ok) {
      html += '<section class="card"><h2 class="h2">2. Install it</h2><div class="btn-row">' +
        '<button type="button" class="btn" id="dl-js">Download data/syllabus.js</button>' +
        '<button type="button" class="btn btn-secondary" id="dl-json">Download normalised JSON</button>' +
        '<button type="button" class="btn btn-secondary" id="preview">Preview in the app on this device</button></div>' +
        '<p class="hint">Replace <code>data/syllabus.js</code> in the project with the downloaded file and redeploy. Preview stores a copy in this browser only, so you can look at it before deploying.</p></section>';
    }
    reportEl.innerHTML = html;
    var dj = document.getElementById("dl-js");
    if (dj) {
      dj.onclick = function () { download("syllabus.js", "/* Generated by the PORIDHI admin tool. Validated before export. */\nwindow.PORIDHI_SYLLABUS = " + JSON.stringify(last.data, null, 1) + ";\n", "text/javascript"); };
      document.getElementById("dl-json").onclick = function () { download("syllabus.normalised.json", JSON.stringify(last.data, null, 1), "application/json"); };
      document.getElementById("preview").onclick = function () {
        var ok = S.setOverride(last.data, last.name);
        showCurrent();
        reportEl.insertAdjacentHTML("afterbegin", ok
          ? '<p class="status-ok" role="status">Preview saved. <a href="index.html">Open the app</a> to look at it.</p>'
          : '<p class="status-bad" role="alert">This browser could not store the preview (storage full or blocked).</p>');
      };
    }
  }

  document.getElementById("file").addEventListener("change", function (e) {
    var f = e.target.files && e.target.files[0];
    if (!f) return;
    var fr = new FileReader();
    fr.onload = function () {
      var res = C.importText(String(fr.result), f.name);
      last = res; last.name = f.name;
      render(res, f.name);
    };
    fr.onerror = function () { reportEl.innerHTML = '<p class="status-bad" role="alert">The file could not be read.</p>'; };
    fr.readAsText(f);
  });

  removeBtn.addEventListener("click", function () { S.clearOverride(); showCurrent(); });
  showCurrent();
})();
